# ── Shared extraction rule blocks ───────────────────────────────
# Single source of truth for WHAT counts as an activity / a person and how
# tone is judged. Both the standalone prompts and the combined one are
# assembled from these blocks, so the extraction criteria cannot drift
# between the fast path (one combined call) and the fallback path.

_ACTIVITIES_RULES = """\
Извлеки из записи список активностей — того, ЧТО пользователь \
делал в этот день. Не эмоции, не состояния, не абстрактные темы — только \
конкретные действия или занятия.

Пиши короткие канонические метки в нижнем регистре, в именительном падеже, \
предпочитай общее слово частному. Примеры:
- "программирование" (не "писал код на Python")
- "спорт" (не "ходил в спортзал")
- "чтение" (не "читал книгу Достоевского")
- "встреча с друзьями" (не "виделись с Олей и Петей в кафе")
- "работа", "учёба", "прогулка", "кино", "готовка", "уборка"

Правила:
- Максимум 5 активностей на запись
- Одно слово или короткая фраза (до 30 символов)
- Без эмоций, состояний ("тревога", "усталость", "радость" — это НЕ активности)
- Если действий не упомянуто или запись только про эмоции — пустой массив []"""

_PEOPLE_RULES = """\
Извлеки упоминания людей — имена \
собственные ИЛИ родственные/социальные роли (мама, папа, бабушка, дедушка, \
брат, сестра, тётя, дядя, муж, жена, парень, девушка, друг, подруга, \
коллега, начальник, психолог и т.п.).

ПРАВИЛА ВЫБОРА ИМЕНИ:
- Если человек упомянут с ролью+именем ("тётя Лена", "Дядя Серёжа", "брат Илья", \
"подруга Маруся") — извлекай ТОЛЬКО имя ("Лена", "Серёжа", "Илья", "Маруся"). \
Не объединяй роль и имя в одну строку.
- Если упомянут "Семья Хачика", "семья брата" — извлекай главного человека \
("Хачик" из "Семья Хачика", "брат" если без имени).
- Если упомянуто имя+фамилия ("Хачик Мкртчян") — только имя ("Хачик").
- Если человек упомянут ТОЛЬКО ролью без имени ("мама позвонила", "брат пришёл") \
— извлекай роль в нижнем регистре.

ПРАВИЛА ФОРМАТА:
- Имена пиши в именительном падеже с заглавной буквы ("Оля", а не "Олей"; \
"Маруся", а не "Марусе"). Если не знаешь нужную форму — пиши имя как в тексте, \
СИМВОЛ-В-СИМВОЛ. Не "русифицируй", не сокращай, не подгоняй под привычные формы. \
"Мари" остаётся "Мари", не "Марь". "Жорж" остаётся "Жорж", не "Жора".
- Роли пиши с маленькой буквы и в именительном падеже ("мама", "брат").
- НЕ извлекай местоимения ("она", "он", "они", "это", "тот") — они не люди.
- НЕ извлекай абстрактные роли "друг", "подруга", "друзья", "приятель", "знакомый" \
— они не идентифицируют конкретного человека.
- НЕ извлекай "автор" / "пользователь" / "я" — это сам пишущий, его не считаем.
- НЕ извлекай животных ("кот", "собака", "лиса"), вымышленных персонажей, бренды, \
места — только реальных людей.
- Не выдумывай и не сокращай слова — если не уверен в форме, оставь как в тексте.

ПРАВИЛА ТОНА (ОТНОСИТЕЛЬНО ЭТОГО ЧЕЛОВЕКА, НЕ ВСЕГО ДНЯ):
- "positive" — текст ЯВНО описывает позитив со стороны или насчёт человека: \
помог, поддержал, тёплое общение, приятный совместный момент.
- "negative" — текст ЯВНО описывает конфликт, обиду, разочарование, плохое \
влияние или что человек сделал что-то плохое.
- "neutral" — нейтральное упоминание: просто виделись, говорили, человек был \
рядом, упоминается без эмоционального заряда.

ВАЖНО ПРО ТОН: оценка дня {rating}/10 — это про весь день, а не про человека. \
Не наследуй настроение дня. Если человек упомянут вскользь без явной оценки \
("позвонил бабушке"), ставь "neutral", даже если день плохой.
По умолчанию — "neutral". "positive" и "negative" только когда есть явные \
маркеры эмоции В АДРЕС этого человека.
- Если людей не упомянуто или речь только о себе — пустой массив []"""

